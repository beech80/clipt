create function clipt_private.record_content_boost_event(p_boost_id uuid,p_event_type text)
returns boolean language plpgsql security definer set search_path='' as $$
declare actor uuid:=auth.uid(); campaign public.content_boosts%rowtype;
begin
 if actor is null or coalesce((auth.jwt()->>'is_anonymous')::boolean,false)
  or not clipt_private.account_available() then raise exception 'Authenticated account required' using errcode='42501'; end if;
 if p_event_type not in ('impression','post_view','profile_visit','follow') then
  raise exception 'Unknown Boost event' using errcode='22023'; end if;
 select b.* into campaign from public.content_boosts b join public.posts p on p.id=b.post_id
 where b.id=p_boost_id and b.user_id<>actor and b.invalidated_at is null
  and b.activated_at<=statement_timestamp() and b.expires_at>statement_timestamp()
  and p.user_id=b.user_id and p.is_published is true and not p.moderation_hidden
  and p.is_premium is not true and p.is_subscriber_only is not true and p.required_tier_id is null
  and not clipt_private.blocked_with(b.user_id);
 if not found then return false; end if;
 if p_event_type in ('profile_visit','follow') and campaign.package_code<>'squad_recruit' then return false; end if;
 if p_event_type='follow' and not exists(select 1 from public.follows f where f.follower_id=actor
  and f.following_id=campaign.user_id and f.created_at>=campaign.activated_at and f.created_at<=campaign.expires_at) then return false; end if;
 insert into public.content_boost_events(boost_id,viewer_id,event_type)
 values(campaign.id,actor,p_event_type) on conflict(boost_id,viewer_id,event_type) do nothing;
 return found;
end $$;
revoke all on function clipt_private.record_content_boost_event(uuid,text) from public,anon;
grant execute on function clipt_private.record_content_boost_event(uuid,text) to authenticated;
create function public.record_content_boost_event(p_boost_id uuid,p_event_type text)
returns boolean language sql security invoker set search_path='' as $$
 select clipt_private.record_content_boost_event(p_boost_id,p_event_type);
$$;
revoke all on function public.record_content_boost_event(uuid,text) from public,anon;
grant execute on function public.record_content_boost_event(uuid,text) to authenticated;

-- Hide Stream Surge from launch responses without deleting its package or any
-- historical transactions. Keep server-calculated membership discounts.
create or replace function public.get_boost_economy() returns jsonb
language sql stable security invoker set search_path='' as $$
 with economy as (select clipt_private.boost_economy() value), visible as (
  select coalesce(jsonb_agg(package order by (package->>'base_price')::integer,package->>'code'),'[]'::jsonb) packages
  from economy cross join lateral jsonb_array_elements(value->'packages') package
  where package->>'code'<>'stream_surge'
 ) select (economy.value-'packages'-'weekly_squad_blast') || jsonb_build_object(
  'packages',visible.packages,'weekly_content_boost_entitled',false) from economy,visible;
$$;

