create function clipt_private.my_content_boosts() returns jsonb
language sql stable security definer set search_path='' as $$
 select coalesce(jsonb_agg(to_jsonb(result) order by result.activated_at desc),'[]'::jsonb) from (
  select b.id,b.original_post_id as post_id,b.package_code,b.base_price,b.discount_percent,b.token_cost,
   b.funding_source,b.entitlement_week,b.activated_at,b.expires_at,
   case when b.invalidated_at is not null or b.post_id is null then 'invalidated'
    when b.expires_at<=statement_timestamp() then 'expired' else 'active' end as state,
   jsonb_build_object(
    'promotional_impressions',(select count(*) from public.content_boost_events e where e.boost_id=b.id and e.event_type='impression'),
    'attributed_post_views',(select count(*) from public.content_boost_events e where e.boost_id=b.id and e.event_type='post_view'),
    'attributed_profile_visits',(select count(*) from public.content_boost_events e where e.boost_id=b.id and e.event_type='profile_visit'),
    'attributed_follows',(select count(*) from public.content_boost_events e where e.boost_id=b.id and e.event_type='follow'),
    'campaign_window_likes',(select count(*) from public.likes l where l.post_id=b.original_post_id and l.created_at between b.activated_at and least(b.expires_at,statement_timestamp())),
    'campaign_window_comments',(select count(*) from public.comments c where c.post_id=b.original_post_id and c.created_at between b.activated_at and least(b.expires_at,statement_timestamp())),
    'campaign_window_shares',(select count(*) from public.external_shares s where s.post_id=b.original_post_id and s.created_at between b.activated_at and least(b.expires_at,statement_timestamp())),
    'total_post_views',(select count(*) from public.post_views v where v.post_id=b.original_post_id)
   ) analytics
  from public.content_boosts b where b.user_id=auth.uid() order by b.activated_at desc limit 50
 ) result;
$$;
revoke all on function clipt_private.my_content_boosts() from public,anon;
grant execute on function clipt_private.my_content_boosts() to authenticated;
create or replace function public.get_my_content_boosts() returns jsonb
language sql stable security invoker set search_path='' as $$
 select clipt_private.my_content_boosts();
$$;

-- Keep the free weekly Squad Blast aligned with photo support and account bans.
create or replace function clipt_private.redeem_weekly_squad_blast(p_post_id uuid,p_idempotency_key uuid,p_expected_week date)
returns uuid language plpgsql security definer set search_path='' as $$
declare actor uuid:=auth.uid(); target public.posts%rowtype; prior public.content_boosts%rowtype;
 package public.boost_packages%rowtype; activated timestamptz; week_start date;
 economy jsonb; result uuid:=gen_random_uuid();
begin
 if actor is null or coalesce((auth.jwt()->>'is_anonymous')::boolean,false)
  or not clipt_private.account_available() then
  raise exception 'Authenticated account and enrolled MFA verification required' using errcode='42501'; end if;
 if not exists(select 1 from auth.users u where u.id=actor and u.deleted_at is null
  and (u.banned_until is null or u.banned_until<=statement_timestamp())) then
  raise exception 'Account is not eligible to activate Boosts' using errcode='42501'; end if;
 if p_post_id is null or p_idempotency_key is null or p_expected_week is null then
  raise exception 'Invalid weekly Boost request' using errcode='22023'; end if;
 select * into target from public.posts where id=p_post_id for update;
 insert into public.token_wallets(user_id) values(actor) on conflict do nothing;
 perform 1 from public.token_wallets where user_id=actor for update;
 select * into prior from public.content_boosts where user_id=actor and idempotency_key=p_idempotency_key;
 if found then
  if prior.original_post_id<>p_post_id or prior.funding_source<>'premium_weekly'
   or prior.entitlement_week<>p_expected_week then raise exception 'Idempotency conflict' using errcode='22023'; end if;
  return prior.id;
 end if;
 economy:=clipt_private.boost_economy();
 if economy->>'membership'<>'premium' then raise exception 'Active Premium membership required' using errcode='42501'; end if;
 activated:=clock_timestamp();week_start:=clipt_private.utc_boost_week(activated);
 if p_expected_week<>week_start then raise exception 'Weekly entitlement changed; refresh and confirm again' using errcode='22023'; end if;
 if exists(select 1 from public.content_boosts where user_id=actor and funding_source='premium_weekly' and entitlement_week=week_start) then
  raise exception 'Weekly Squad Blast already redeemed' using errcode='23505'; end if;
 if target.id is null or target.user_id<>actor or target.is_published is not true
  or target.is_premium is true or target.is_subscriber_only is true or target.moderation_hidden
  or target.required_tier_id is not null
  or (nullif(target.video_url,'') is null and nullif(target.image_url,'') is null)
  or target.post_type not in ('clipt','clipts','video','photo','post') or target.created_at>statement_timestamp() then
  raise exception 'Clipt or screenshot is not eligible for boosting' using errcode='42501'; end if;
 if exists(select 1 from public.content_boosts where post_id=p_post_id and invalidated_at is null and expires_at>activated) then
  raise exception 'This Clipt already has an active Boost' using errcode='23505'; end if;
 select * into package from public.boost_packages where code='squad_blast';
 if package.code is null or package.target_kind<>'clipt' or package.duration_seconds<>86400 then
  raise exception 'Squad Blast configuration unavailable' using errcode='22023'; end if;
 insert into public.content_boosts(id,user_id,post_id,original_post_id,package_code,idempotency_key,
  base_price,discount_percent,token_cost,activated_at,expires_at,ledger_id,funding_source,entitlement_week)
 values(result,actor,p_post_id,p_post_id,'squad_blast',p_idempotency_key,package.base_price,0,0,
  activated,activated+interval '24 hours',null,'premium_weekly',week_start);
 return result;
end $$;

