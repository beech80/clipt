-- Pure selection. No engagement, Trophy, view, or ranking counters are changed.
create function clipt_private.boost_opportunities(p_game_id uuid)
returns table(boost_id uuid,post_id uuid,creator_id uuid,package_code text,expires_at timestamptz)
language sql stable security definer set search_path='' as $$
 select b.id,b.post_id,b.user_id,b.package_code,b.expires_at
 from public.content_boosts b join public.posts p on p.id=b.post_id
 where (select clipt_private.account_available()) and auth.uid() is not null
  and coalesce((auth.jwt()->>'is_anonymous')::boolean,false)=false and p.user_id<>auth.uid()
  and b.invalidated_at is null and b.activated_at<=statement_timestamp() and b.expires_at>statement_timestamp()
  and p.user_id=b.user_id and p.is_published is true and p.is_premium is not true
  and p.is_subscriber_only is not true and not p.moderation_hidden and p.required_tier_id is null
  and (nullif(p.video_url,'') is not null or nullif(p.image_url,'') is not null)
  and p.post_type in ('clipt','clipts','video','photo','post') and not clipt_private.blocked_with(p.user_id)
  and not exists(select 1 from public.content_boost_events e where e.boost_id=b.id
   and e.viewer_id=auth.uid() and e.event_type='impression')
  and (p_game_id is null or p.game_id=p_game_id)
  and (
   (b.package_code='king_now' and p_game_id is not null and p.game_id=p_game_id)
   or (b.package_code='squad_blast' and (
    auth.uid() in (select f.follower_id from public.follows f where f.following_id=b.user_id
      and f.follower_id<>b.user_id order by f.created_at desc,f.follower_id limit 25)
    or (p.game_id is not null and exists(select 1 from public.posts interest where interest.user_id=auth.uid()
      and interest.game_id=p.game_id and interest.is_published is true and not interest.moderation_hidden))))
   or (b.package_code='hidden_gem' and p.created_at<=b.activated_at-interval '6 hours'
    and not exists(select 1 from public.post_views seen where seen.post_id=p.id and seen.viewer_id=auth.uid())
    and (p.game_id is null or exists(select 1 from public.posts interest where interest.user_id=auth.uid()
      and interest.game_id=p.game_id and interest.is_published is true and not interest.moderation_hidden)))
   or (b.package_code='squad_recruit' and p.game_id is not null
    and not exists(select 1 from public.follows existing where existing.follower_id=auth.uid() and existing.following_id=b.user_id)
    and (p_game_id=p.game_id or exists(select 1 from public.posts interest where interest.user_id=auth.uid()
      and interest.game_id=p.game_id and interest.is_published is true and not interest.moderation_hidden)))
   or (b.package_code='chain_reaction' and (
    auth.uid() in (select f.follower_id from public.follows f where f.following_id=b.user_id
      and f.follower_id<>b.user_id order by f.created_at desc,f.follower_id limit 5)
    or exists(select 1 from (
      select l.user_id from public.likes l where l.post_id=b.post_id and l.user_id<>b.user_id
       and l.created_at between b.activated_at and statement_timestamp()
      union select c.user_id from public.comments c where c.post_id=b.post_id and c.user_id<>b.user_id
       and length(btrim(c.content))>0 and c.created_at between b.activated_at and statement_timestamp()
      union select s.user_id from public.external_shares s where s.post_id=b.post_id and s.user_id<>b.user_id
       and s.created_at between b.activated_at and statement_timestamp()
     ) genuine_actor cross join lateral (
      select f.follower_id from public.follows f where f.following_id=genuine_actor.user_id
       and f.follower_id<>b.user_id and f.follower_id<>genuine_actor.user_id
      order by f.created_at desc,f.follower_id limit 5
     ) expansion where expansion.follower_id=auth.uid())))
  ) order by b.activated_at desc,b.id limit 20;
$$;
revoke all on function clipt_private.boost_opportunities(uuid) from public,anon;
grant execute on function clipt_private.boost_opportunities(uuid) to authenticated;

