import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import postcss from 'postcss';

test('short landscape preserves controller touch targets and reserves feed clearance', async () => {
  const controls = postcss.parse(await readFile(new URL('../../src/components/GameBoyControls.css', import.meta.url), 'utf8'));
  const feed = postcss.parse(await readFile(new URL('../../src/pages/clipt-console.css', import.meta.url), 'utf8'));
  const findShort = root => root.nodes.find(node => node.type === 'atrule' && node.name === 'media' && node.params === '(orientation: landscape) and (max-height: 500px)');
  const controller = findShort(controls);
  const landscape = findShort(feed);
  assert.ok(controller);
  assert.ok(landscape);
  const declarations = (scope, selector) => Object.fromEntries(scope.nodes.find(node => node.selector === selector).nodes.map(node => [node.prop, node.value]));
  assert.equal(declarations(controller, '.gameboy-controls.clipt-controller').height, 'calc(128px + env(safe-area-inset-bottom,0px))');
  assert.equal(declarations(controls, '.clipt-controller-action').width, '44px');
  assert.equal(declarations(controls, '.clipt-controller-action').height, '44px');
  assert.equal(declarations(landscape, '.clipt-fyp-track')['min-height'], '0');
  assert.equal(declarations(landscape, '.clipt-fyp-track').height, '100%');
  assert.equal(declarations(landscape, '.clipt-fyp').position, 'fixed');
  assert.doesNotMatch(declarations(landscape, '.clipt-fyp').inset, /64px/);
  assert.equal(declarations(landscape, '.clipt-cinematic-media').inset, '0');
  assert.equal(declarations(landscape, '.clipt-cinematic-media').height, '100%');
  assert.match(declarations(landscape, 'body:has(.clipt-controller-feed[data-expanded="true"]) .clipt-fyp').right, /216px/);
  assert.equal(declarations(landscape, 'body:has(.clipt-controller-feed[data-expanded="true"]) .clipt-cinematic-media').height, 'calc(100% - 52px)');
  assert.equal(declarations(landscape, 'body:has(.clipt-controller-feed[data-expanded="true"]) .clipt-feed-tabs').position, 'fixed');
  assert.equal(declarations(landscape, 'body:has(.clipt-controller-feed[data-expanded="true"]) .clipt-fyp-track')['grid-row'], '1');
  assert.equal(declarations(landscape, 'body:has(.clipt-controller-feed[data-expanded="true"]) .clipt-controller-body')['max-height'], 'calc(100% - 56px)');
  assert.equal(declarations(landscape, '.clipt-feed-tabs').display, 'none');
  assert.equal(declarations(landscape, '.clipt-messages').height, 'auto');
  assert.equal(declarations(landscape, '.clipt-messages')['min-height'], '320px');
  assert.equal(declarations(landscape, '.clipt-messages > .grid')['min-height'], '260px');
  assert.equal(declarations(landscape, '.clipt-message-picker[role="dialog"]')['overflow-y'], 'auto');
  assert.equal(declarations(landscape, '.clipt-fyp .clipt-fyp-slide > article').display, 'block');
  assert.equal(declarations(landscape, '.clipt-fyp .clipt-fyp-slide > article').animation, 'none');
  assert.equal(declarations(landscape, '.clipt-cinematic-media')['min-height'], '0');
  assert.equal(declarations(landscape, '.clipt-fyp-slide > article .clipt-cinematic-header button')['white-space'], 'nowrap');
  assert.equal(declarations(feed, '.clipt-fyp-track')['scroll-snap-type'], 'x mandatory');
  const connections = declarations(feed, '.clipt-connections-dialog[role="dialog"]');
  assert.equal(connections.transform, 'translateX(-50%)');
  assert.equal(connections['overflow-y'], 'auto');
  assert.match(connections.top, /safe-area-inset-top/);
  assert.match(connections['max-height'], /100dvh/);
  assert.equal(declarations(feed, '.clipt-fyp-slide > article .clipt-cinematic-caption p > button').display, 'none');
  const compact = controls.nodes.findLast(node => node.type === 'atrule' && node.params === '(orientation: landscape) and (max-height: 500px)' && node.nodes.some(child=>child.selector==='.gameboy-controls.clipt-controller.clipt-controller-feed'));
  const pageConsole = controls.nodes.findLast(node => node.type === 'atrule' && node.params === '(orientation: landscape) and (max-height: 500px)' && node.nodes.some(child=>child.selector==='.gameboy-controls.clipt-controller[data-page-controller]'));
  assert.equal(declarations(pageConsole,'.gameboy-controls.clipt-controller[data-page-controller]').height,'calc(128px + env(safe-area-inset-bottom,0px))');
  assert.equal(declarations(pageConsole,'body:has(.clipt-controller[data-page-controller]) .page-content')['padding-bottom'],'calc(152px + env(safe-area-inset-bottom,0px))');
  assert.equal(declarations(compact, '.gameboy-controls.clipt-controller.clipt-controller-feed').height, '44px');
  const expandedDock = declarations(compact, '.gameboy-controls.clipt-controller.clipt-controller-feed[data-expanded="true"]');
  assert.match(expandedDock.height, /100dvh/);
  assert.equal(expandedDock.overflow, 'hidden');
  assert.equal(declarations(compact, '.clipt-controller-feed[data-expanded="true"] .clipt-controller-body')['overflow-y'], 'auto');
  assert.equal(declarations(compact, '.clipt-controller-feed[data-expanded="true"] .clipt-controller-body').gap, '6px');
  assert.equal(declarations(compact, '.clipt-controller-feed[data-expanded="true"] .clipt-controller-toggle').position, 'absolute');
  assert.equal(declarations(compact, '.clipt-controller-feed::before').display, 'none');
  assert.equal(expandedDock.width, 'min(216px,calc(100vw - 24px))');
  assert.equal(declarations(controls, '.gameboy-controls.clipt-controller.clipt-controller-feed').height, 'calc(122px + env(safe-area-inset-bottom,0px))');
  assert.equal(declarations(controls, '.clipt-controller-feed .clipt-controller-action').position, 'absolute');
  assert.equal(declarations(controls, '.clipt-controller-feed .clipt-controller-actions').width, '108px');
  assert.equal(declarations(controls, '.clipt-controller-like').top, '0');
  assert.equal(declarations(controls, '.clipt-controller-trophy').left, '0');
  assert.equal(declarations(controls, '.clipt-controller-comment').right, '0');
  assert.equal(declarations(controls, '.clipt-controller-follow').bottom, '0');
  assert.equal(declarations(compact, '.clipt-controller-feed .clipt-controller-action').position, 'absolute');
  assert.equal(declarations(compact, '.clipt-controller-feed .clipt-controller-actions').width, '160px');
  assert.equal(declarations(compact, '.clipt-controller-feed[data-expanded="true"] .clipt-controller-joystick')['grid-row'], '1');
  assert.equal(declarations(compact, '.clipt-controller-feed[data-expanded="true"] .clipt-controller-joystick')['align-self'], 'center');
  assert.equal(declarations(compact, '.clipt-controller-feed[data-expanded="true"] .clipt-controller-joystick')['justify-self'], 'center');
  assert.equal(declarations(compact, '.clipt-controller-feed .clipt-controller-actions')['justify-self'], 'center');
  assert.equal(declarations(compact, '.clipt-controller-feed .clipt-controller-like').top, '0');
  assert.equal(declarations(compact, '.clipt-controller-feed .clipt-controller-comment').top, '58px');
  assert.equal(declarations(compact, '.clipt-controller-feed .clipt-controller-follow').bottom, '0');
  assert.equal(declarations(compact, '.clipt-controller-feed .clipt-controller-secondary').display, 'contents');
  assert.equal(declarations(compact, '.clipt-controller-feed .clipt-controller-secondary button:first-child').order, '0');
  assert.equal(declarations(compact, '.clipt-controller-feed .clipt-controller-home').order, '1');
  assert.equal(declarations(compact, '.clipt-controller-feed .clipt-controller-secondary button:last-child').order, '2');
  const conversation = Object.fromEntries(feed.nodes.findLast(node => node.selector === '.clipt-engagement-hud[role="dialog"]').nodes.map(node => [node.prop,node.value]));
  assert.equal(conversation.left, '50%');
  assert.equal(conversation['z-index'], '70');
  assert.equal(conversation.height, 'auto');
  assert.equal(conversation['overflow-y'], 'auto');
  const shortHeader=feed.nodes.find(node => node.type === 'atrule' && node.params === '(orientation: landscape) and (max-height: 320px)');
  assert.equal(declarations(shortHeader,'.gameboy-controls.clipt-controller-feed[data-expanded="true"] .clipt-controller-body')['margin-top'],'48px');
  const comments = feed.nodes.find(node => node.type === 'atrule' && node.params === '(orientation: landscape) and (max-height: 500px)' && node.nodes.some(child=>child.selector==='body:has(.clipt-fyp) .clipt-engagement-hud[role="dialog"]'));
  const docked = declarations(comments, 'body:has(.clipt-fyp) .clipt-engagement-hud[role="dialog"]');
  assert.equal(docked.width, expandedDock.width);
  assert.equal(docked.transform, 'none');
  assert.match(docked.height, /100dvh/);
  assert.ok(comments.nodes.some(node => node.selector?.includes('.clipt-controller-feed,') && node.nodes.some(declaration => declaration.prop === 'visibility' && declaration.value === 'hidden')));
});
